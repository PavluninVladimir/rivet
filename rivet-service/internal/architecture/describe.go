package architecture

import (
	"strings"
)

// Задание роли architect для задачи описания архитектуры (спека
// backend/project-architecture «Задача описания архитектуры»): шаг
// describe процесса задачи вида architecture.

// DescribeMarker открывает задание describe. По нему fake-агент e2e-стенда
// узнаёт задание и кладёт в ветку фикстуру описания.
const DescribeMarker = "[rivet:architecture-describe]"

// DescribeCriteria — фиксированные acceptance criteria задачи описания.
// Ревьюер сверяет описание с кодом репозитория по каждому из них.
func DescribeCriteria() []string {
	return []string{
		"Контейнеры описания соответствуют развёртываемым частям репозитория: приложениям, сервисам, базам данных и очередям",
		"Внешние системы описания соответствуют реальным интеграциям в коде",
		"Описание в " + DefaultDir + " проходит проверку `architecture validate` без ошибок",
		"Представления в " + DefaultDir + "/views актуальны: проверка `architecture views --check` проходит",
		"ERD соответствует схеме хранения в коде: атрибуты, ключи и связи объектов данных взяты из миграций, схем, моделей или структур хранилища",
		"Ключевые сценарии отражают реальные потоки вызовов в коде",
		"Значимые решения (хранилище, фреймворк, развёртывание, аутентификация, интеграции) зафиксированы в ADR со статусом accepted и ссылками на элементы модели",
	}
}

// DescribePrompt — текст задания шага describe для роли architect.
func DescribePrompt() string {
	var b strings.Builder
	b.WriteString(DescribeMarker + "\n")
	b.WriteString(`Опиши текущую архитектуру (as-is) репозитория в каталоге ` + DefaultDir + `/ в формате описания архитектуры Rivet (` + Format + `).

Порядок работы:
1. Изучи репозиторий: что в нём развёртывается отдельно (приложения, сервисы, воркеры, базы данных, очереди), из каких крупных частей они состоят, с какими внешними системами интегрируются, где и как всё запускается.
2. Если каталога ` + DefaultDir + ` нет, создай описание командой "$RIVET_RUNNER_BIN" architecture init -dir ` + DefaultDir + ` -system "<название системы>". Если описание уже есть, сверь его с кодом и исправь расхождения, ничего не удаляй без причины.
3. Заполни в architecture.yaml поле description: назначение системы в одном-двух предложениях. Принципы (principles) добавляй, только если они явно видны в коде или документации.
4. Опиши слои модели в model/*.yaml. Идентификаторы элементов с префиксом слоя: biz., app., data., tech.
5. Перед завершением запусти "$RIVET_RUNNER_BIN" architecture validate -dir ` + DefaultDir + ` и "$RIVET_RUNNER_BIN" architecture views -dir ` + DefaultDir + `. Исправь все ошибки проверки, представления в views/ не правь руками.

Слои модели:
`)
	for _, l := range builtinLayers {
		b.WriteString("- " + l.title + ": " + l.prompt + "\n")
	}
	b.WriteString(`
Нотация C4 строится из модели автоматически:
- actor и role становятся людьми;
- component без родителя по composition становится контейнером описываемой системы, а component внутри контейнера (composition) его компонентом;
- system-software со связью access к data-object становится базой данных.

Уточняй вывод свойствами элемента в props, где вывод по умолчанию неверен:
- c4: person, system, container, database, queue, component или none. Внешнюю систему, с которой интегрируется код (GitHub, платёжный шлюз, почта), опиши компонентом верхнего уровня с c4: system и external: true. Очередь опиши с c4: queue. Вспомогательные элементы, которым не место на схемах C4, помечай c4: none.
- technology: язык, фреймворк или продукт контейнера, например "Go, net/http" или "PostgreSQL 16". Укажи его у каждого контейнера и базы данных.
- external: true только у элемента без родителя.

Называй контейнеры и компоненты так же, как они называются в коде. Связи между контейнерами описывай serving, flow, triggering и access с mode. Бизнес-процессы в BPMN описывай, только если они явно видны в коде.

Данные (ERD):
- У каждого data-object перечисли атрибуты в поле attributes по коду: миграциям, схемам баз, моделям ORM, структурам файловых и JSON-хранилищ. Атрибут: name, type, pk, fk ({to: <data-object>, attribute: <атрибут>}), nullable, unique, description.
- У каждого объекта с атрибутами должен быть первичный ключ (pk). Связи между объектами выводятся из fk. Явную связь association с cardinality (one-to-one, one-to-many, many-to-one, many-to-many) и label добавляй для связи многие-ко-многим и для смысловых подписей.
- Хранилище (system-software со связью access к объектам данных) получает свою ERD автоматически.

Сценарии:
- Опиши от трёх до семи ключевых сценариев, которые действительно есть в коде: найди обработчик, проследи вызовы. Файл scenarios/<id>.yaml, идентификатор с префиксом sc., например sc.contact-create.
- Шаг: {from, to, message, kind}, kind: sync, async, return или self. Участники: элементы actor, role, component, system-software, node или system. Ветвления и повторы описывай блоками alt (список веток {when, steps}), opt и loop ({when, steps}).
- Перечисли идентификаторы сценариев в поле scenarios манифеста architecture.yaml: файлы вне индекса не читаются.

Решения (ADR):
- Зафиксируй значимые решения, видимые в коде: хранилище, фреймворк, способ развёртывания, аутентификацию, интеграции. Файл adr/NNNN-<slug>.md, нумерация подряд с 0001.
- В начале файла YAML front matter между строками ---: number, title, status: accepted, date (дата задачи, ГГГГ-ММ-ДД), elements (идентификаторы элементов модели).
- В теле разделы ## Контекст, ## Решение, ## Последствия и, если есть, ## Рассмотренные варианты. В контексте ссылайся на файлы репозитория, из которых видно решение.
- Перечисли имена файлов без расширения в поле decisions манифеста.

Не выдумывай сценарии и решения, которых нет в коде: ревьюер сверяет их с репозиторием.

Меняй только файлы внутри ` + DefaultDir + `/: проверка шага test проваливается, если ветка меняет что-то ещё.
`)
	return b.String()
}
